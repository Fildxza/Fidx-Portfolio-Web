/**
 * Curated source of truth for project case studies.
 *
 * Hybrid model: this registry holds the *narrative* (what a project is, what
 * was built, how it was verified); live GitHub metadata (stars, last push) is
 * merged in at request time by `buildFeaturedProjects`. Nothing here is a
 * statistic — every claim must be traceable to the resume, the repository's own
 * README, or its source layout, and each entry says which in `evidence`.
 *
 * To add a project: append an entry, set `published: true` once you are happy
 * for it to appear publicly, and keep `visibility` honest — a private
 * repository must have `repoUrl: null`.
 */

