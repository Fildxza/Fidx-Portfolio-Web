  title: string;
  /** One sentence that communicates value, shown on the card. */
  summary: string;
  categories: ProjectCategory[];
  /** Honest development stage, e.g. "Prototype". */
  status: string;
  visibility: "public" | "private";
  repoUrl: string | null;
  repoOwner: string;
  contributionType: "owner" | "collaborator";
  liveUrl: string | null;
  featured: boolean;
  /** Only published entries are shown on the site. */
  published: boolean;

  overview: string;
  problem: string;
  audience: string[];
  contribution: string;
  architecture: { caption: string; nodes: FlowNode[] };
  decisions: string[];
  stack: string[];
  features: { name: string; status: FeatureStatus; detail?: string }[];
  security: string[];
  limitations: string[];
  future: string[];
  /** How the content above was verified — shown to readers. */
  evidence: string;
  /** Optional note about the client, shown under the title (e.g. published contact details). */
  clientNote?: string;
  relatedLab?: { label: string };
  /** Screenshot used as the card thumbnail instead of the generated architecture thumbnail. */
  cover?: { src: string; alt: string; /** True when the image is made artwork, not a screenshot; the card says so. */ illustration?: boolean };
  /** Real screenshots of the running project, shown on its case-study page only. */
  gallery?: { src: string; alt: string; caption: string; width?: number; height?: number }[];
  /** Heading of the gallery section; defaults to "Screenshots". */
  galleryTitle?: string;
  /** Note shown under the gallery, e.g. what data the screenshots show. */
  galleryNote?: string;
