  categories: ProjectCategory[];
  /** Honest development stage, e.g. "Prototype". */
  status: string;
  visibility: "public" | "private";
  repoUrl: string | null;
  repoOwner: string;
  contributionType: "owner" | "collaborator";
  liveUrl: string | null;
  featured: boolean;
  /** Only published entries are shown on the site. */
  published: boolean;

  overview: string;
  problem: string;
  audience: string[];
  contribution: string;
  architecture: { caption: string; nodes: FlowNode[] };
